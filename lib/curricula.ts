/**
 * Starting points for the calculator.
 *
 * Every entry is the *common* first-year layout of the national LMD
 * programme (the ministry canevas that institutions adapt): the unit names
 * are the ones students meet in class, and credits total 30 per semester.
 * Coefficients are the usual ones, but institutions do shift them — the same
 * Analyse 1 is coefficient 3 in one faculty and 4 in another — so nothing
 * here is presented as the official record. The student corrects the rows
 * against their own « بطاقة التكوين »; the calculator only does the
 * arithmetic.
 */

export type CurriculumUnit = { name: string; credits: number; coef: number };

export type Curriculum = {
  id: string;
  /** Programme name as students say it. */
  name: string;
  /** Grouping label used by the picker. */
  field: string;
  s1: CurriculumUnit[];
  s2: CurriculumUnit[];
};

type Row = [name: string, credits: number, coef: number];

const unit = ([name, credits, coef]: Row): CurriculumUnit => ({ name, credits, coef });

const entry = (id: string, name: string, field: string, s1: Row[], s2: Row[]): Curriculum => ({
  id,
  name,
  field,
  s1: s1.map(unit),
  s2: s2.map(unit),
});

