export const curriculumById: Record<string, Curriculum> = Object.fromEntries(
  curricula.map((item) => [item.id, item]),
);

/** Field order for the picker: the order above, first appearance wins. */
export const curriculumGroups: { field: string; items: Curriculum[] }[] = curricula.reduce(
  (groups, item) => {
    const group = groups.find((entry) => entry.field === item.field);
    if (group) group.items.push(item);
    else groups.push({ field: item.field, items: [item] });
    return groups;
  },
  [] as { field: string; items: Curriculum[] }[],
);
